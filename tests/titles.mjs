import assert from 'node:assert/strict';
import { initialGame,settleGame,publicProjection } from '../src/core/game-engine.js';
import { computeAttrs,cultivationRate,combatPower } from '../src/systems/character.js';
import { bindServerRights,founderMultiplier } from '../src/core/shards.js';
import { simulateDuel } from '../src/systems/combat.js';
let checks=0;const check=(value,label)=>{assert(value,label);checks++;};
const now=Date.UTC(2026,9,4),a=initialGame(now),b=initialGame(now),base=computeAttrs(a);
a.player.title='title_creator';a.owned=['title_creator'];
check(founderMultiplier(a)===1,'editable snapshot cannot grant creator bonus');
bindServerRights(a,[],'title_creator');check(founderMultiplier(a)===1,'unowned equipped title cannot grant bonus');
bindServerRights(a,['title_creator'],null);check(founderMultiplier(a)===1,'owned but unequipped title has no bonus');
bindServerRights(a,['title_creator'],'title_creator');check(founderMultiplier(a)===100,'verified equipped founder title grants bonus');
const attrs=computeAttrs(a);for(const key of ['hpMax','mpMax','atk','def','spd'])check(attrs[key]===base[key]*100,key+' scales exactly');
check(Math.abs(cultivationRate(a)/cultivationRate(b)-100)<1e-9,'cultivation rate scales exactly');
check(combatPower(a)>combatPower(b)*90,'PVE power reflects large bonus');
assert.deepEqual(computeAttrs(a,{competitive:true}),computeAttrs(b));checks++;
assert.deepEqual(simulateDuel(a,b,()=>.6),simulateDuel(b,b,()=>.6));checks++;
check(publicProjection(a).power===combatPower(b),'real power board uses competitive attributes');
const progressed=settleGame(b,'sync',[],now+10,['title_creator'],'title_creator');
const normal=settleGame(b,'sync',[],now+10);
check(Math.abs(progressed.state.player.totalCultivation/normal.state.player.totalCultivation-100)<1e-9,'server offline settlement applies founder rate');
check(founderMultiplier(progressed.state)===100,'server intermediate projection retains trusted title only');
check(founderMultiplier(JSON.parse(JSON.stringify(progressed.state)))===1,'serialized role cannot carry entitlement authorization');
check(founderMultiplier(settleGame(a,'reset',[],now,['title_creator'],'title_creator').state)===100,'account title survives gameplay reset');
check(founderMultiplier(settleGame(a,'sync',[],now,[],null).state)===1,'revoked or unequipped title loses bonus');
console.log(JSON.stringify({passed:checks}));
